"""Generate review/atlas/atlas.json and review/atlas/ATLAS.md (python -m tests.atlas.report)."""
from __future__ import annotations

import collections
import dataclasses
import json
import os
import sys
import time

from tests.atlas.atlas import DTYPES, OPS, STRUCTURES, VIEWS, enumerate_cells, run_cell, symbol

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "review", "atlas")


def main(argv=None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    only = set(argv)
    cells = [c for c in enumerate_cells(storages=("ram", "file")) if not only or c.op in only]
    t0 = time.time()
    for i, c in enumerate(cells):
        run_cell(c)
        if i % 500 == 0:
            print(f"{i}/{len(cells)} {time.time() - t0:.0f}s", file=sys.stderr, flush=True)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "atlas.json"), "w") as f:
        json.dump([dataclasses.asdict(c) for c in cells], f, indent=0)
    with open(os.path.join(OUT, "ATLAS.md"), "w") as f:
        f.write(render(cells))
    print(summary_line(cells))


def summary_line(cells) -> str:
    n = collections.Counter(c.outcome for c in cells)
    p = collections.Counter(c.path for c in cells if c.outcome == "ok")
    return f"{len(cells)} cells: " + ", ".join(f"{k} {v}" for k, v in n.most_common()) + " | ok paths: " + ", ".join(f"{k} {v}" for k, v in p.most_common())


def render(cells) -> str:
    out = ["# Operation atlas (generated)", "",
           "Generated by `python -m tests.atlas.report`; design in `review/features/ATLAS.md`. Do not edit.", "",
           "Symbols: ✓ ok, fast kernel · ◐ ok, input written out first (O(n²) op) · ○ ok, generic per-element "
           "virtual access · N ok, NumPy round trip · ✗ **wrong result** · — raises where NumPy gives an answer "
           "(unsupported) · `·` raises, NumPy raises too · blank: operand not available (structure × dtype or view "
           "not offered).", "", summary_line(cells), ""]

    # problems first
    for title, pred in [("Wrong results (✗)", lambda c: c.outcome == "wrong"),
                        ("NumPy round trips (N)", lambda c: c.outcome == "ok" and c.path == "numpy"),
                        ("Generic per-element paths (○)", lambda c: c.outcome == "ok" and c.path == "generic"),
                        ("Unsupported (—)", lambda c: c.outcome == "unsupported")]:
        sel = [c for c in cells if pred(c)]
        out += [f"## {title}: {len(sel)}", ""]
        groups = collections.defaultdict(list)
        for c in sel:
            groups[(c.op, (c.error or ",".join(c.kernels))[:90])].append(c)
        for (op, why), cs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
            keys = ", ".join(sorted({f"{c.dtype}{'x' + c.dtype2 if c.dtype2 else ''}/{c.structure}{'x' + c.structure2 if c.structure2 else ''}/{c.view}" for c in cs})[:8])
            more = f" (+{len(cs) - 8})" if len(cs) > 8 else ""
            out.append(f"* **{op}** ×{len(cs)} — {why or 'no error'}: {keys}{more}")
        out.append("")

    unavailable = collections.Counter((c.structure, c.dtype) for c in cells if c.outcome == "unavailable" and not c.error.startswith("view"))
    views_missing = collections.Counter((c.structure, c.view) for c in cells if c.error.startswith("view"))
    out += ["## Operand availability", "",
            "Structures not offered for a dtype: " + ", ".join(sorted({f"{s}/{d}" for s, d in unavailable})) + ".", "",
            "Views not offered: " + ", ".join(sorted({f"{s}/{v}" for s, v in views_missing})) + ".", ""]

    untraced = collections.Counter(c.op for c in cells if c.outcome == "ok" and not c.kernels)
    out += ["## Cells with no kernel trace", "", "Kernels that set no `debug_trace` name (the path is then inferred "
            "from the counters alone): " + ", ".join(f"{k} ×{v}" for k, v in untraced.most_common()) + ".", ""]

    # per-operation grids (same-operand cells, RAM)
    by = {(c.op, c.structure, c.dtype, c.view): c for c in cells if not c.dtype2 and not c.structure2 and c.storage == "ram"}
    for op in OPS:
        views = [v for v in VIEWS if any((op.name, s, d, v) in by for s in STRUCTURES for d in DTYPES)]
        if not views:
            continue
        out += [f"## {op.name} ({op.group})", "", "| structure / dtype | " + " | ".join(views) + " |",
                "|---|" + "---|" * len(views)]
        for s in STRUCTURES:
            for d in DTYPES:
                row = [by.get((op.name, s, d, v)) for v in views]
                if all(r is None or r.outcome == "unavailable" for r in row):
                    continue
                out.append(f"| {s} / {d} | " + " | ".join(symbol(r) if r else "" for r in row) + " |")
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    main()
